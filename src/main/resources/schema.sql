-- 阶段 1 最小支付核心表结构。仅保存支付意图、尝试、资金事实与投递状态，
-- 不包含账套、凭证、结算或商户余额，因此不构成账务能力。

-- 商户幂等绑定：商户 + 操作类别 + 命名空间 + 幂等键 唯一裁决
CREATE TABLE IF NOT EXISTS merchant_idempotency (
    merchant_id      VARCHAR(64)  NOT NULL,
    operation_type   VARCHAR(32)  NOT NULL,
    namespace        VARCHAR(64)  NOT NULL,
    idempotency_key  VARCHAR(128) NOT NULL,
    payload_digest   VARCHAR(64)  NOT NULL,
    payment_id       VARCHAR(64)  NOT NULL,
    created_at       TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP,
    PRIMARY KEY (merchant_id, operation_type, namespace, idempotency_key)
);

-- 支付单：固定收款意图，不承载渠道重试细节
CREATE TABLE IF NOT EXISTS payment_order (
    payment_id        VARCHAR(64)  NOT NULL PRIMARY KEY,
    merchant_id       VARCHAR(64)  NOT NULL,
    merchant_order_id VARCHAR(128) NOT NULL,
    amount_minor      BIGINT       NOT NULL,
    currency          VARCHAR(3)   NOT NULL,
    status            VARCHAR(24)  NOT NULL,
    posting_status    VARCHAR(24)  NOT NULL,
    version           INT          NOT NULL,
    created_at        TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at        TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uk_payment_merchant_order UNIQUE (merchant_id, merchant_order_id)
);

-- 渠道尝试：固定渠道账户与渠道幂等键，是发送与核查的身份
CREATE TABLE IF NOT EXISTS channel_attempt (
    attempt_id               VARCHAR(64)  NOT NULL PRIMARY KEY,
    payment_id               VARCHAR(64)  NOT NULL,
    operation_id             VARCHAR(64)  NOT NULL,
    channel_id               VARCHAR(32)  NOT NULL,
    channel_account          VARCHAR(64)  NOT NULL,
    provider_idempotency_key VARCHAR(128) NOT NULL,
    status                   VARCHAR(24)  NOT NULL,
    lease_version            INT          NOT NULL DEFAULT 0,
    created_at               TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at               TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uk_attempt_provider_key UNIQUE (channel_id, channel_account, provider_idempotency_key)
);

-- 资金事实：同一操作 + 事实类型 + 渠道事实身份 只允许一条
CREATE TABLE IF NOT EXISTS payment_fact (
    fact_id            VARCHAR(64)  NOT NULL PRIMARY KEY,
    operation_id       VARCHAR(64)  NOT NULL,
    fact_type          VARCHAR(24)  NOT NULL,
    provider_reference VARCHAR(128) NOT NULL,
    amount_minor       BIGINT       NOT NULL,
    currency           VARCHAR(3)   NOT NULL,
    created_at         TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uk_payment_fact UNIQUE (operation_id, fact_type, provider_reference)
);

-- 状态历史：追加写入，不按通知到达顺序覆盖
CREATE TABLE IF NOT EXISTS payment_event (
    history_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    payment_id VARCHAR(64)  NOT NULL,
    status     VARCHAR(24)  NOT NULL,
    detail     VARCHAR(512),
    created_at TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP
);

-- Outbox：与业务写入同事务提交，发布成功前不得丢弃
CREATE TABLE IF NOT EXISTS outbox_record (
    event_id          VARCHAR(64)  NOT NULL PRIMARY KEY,
    aggregate_id      VARCHAR(64)  NOT NULL,
    aggregate_version INT          NOT NULL,
    event_type        VARCHAR(64)  NOT NULL,
    payload           VARCHAR(4000) NOT NULL,
    status            VARCHAR(16)  NOT NULL,
    publish_version   INT          NOT NULL DEFAULT 0,
    created_at        TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP,
    published_at      TIMESTAMP,
    CONSTRAINT uk_outbox_aggregate UNIQUE (aggregate_id, aggregate_version, event_type)
);

-- 模拟消息系统的投递日志：以 event_id 为主键吸收重复投递（不证明端到端 exactly-once）
CREATE TABLE IF NOT EXISTS event_log (
    event_id     VARCHAR(64)  NOT NULL PRIMARY KEY,
    event_type   VARCHAR(64)  NOT NULL,
    payload      VARCHAR(4000) NOT NULL,
    delivered_at TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP
);

-- 模拟渠道场景：按商户订单号指定，仅用于本地验证
CREATE TABLE IF NOT EXISTS mock_channel_scenario (
    merchant_order_id VARCHAR(128) NOT NULL PRIMARY KEY,
    scenario          VARCHAR(32)  NOT NULL
);

-- 模拟渠道交易：以渠道幂等键为主键，重复请求返回原结果
CREATE TABLE IF NOT EXISTS mock_channel_tx (
    provider_idempotency_key VARCHAR(128) NOT NULL PRIMARY KEY,
    status                   VARCHAR(16)  NOT NULL,
    provider_reference       VARCHAR(128) NOT NULL,
    amount_minor             BIGINT       NOT NULL,
    currency                 VARCHAR(3)   NOT NULL,
    created_at               TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP
);

-- ===== 阶段 2：账务核心与退款 =====

-- 币种元数据：金额解释依据，历史金额不能随配置被重新解释
CREATE TABLE IF NOT EXISTS currency_metadata (
    currency            VARCHAR(3) NOT NULL PRIMARY KEY,
    minor_unit_exponent INT        NOT NULL,
    version             INT        NOT NULL,
    effective_at        TIMESTAMP  NOT NULL DEFAULT CURRENT_TIMESTAMP
);

-- 账套：法律主体、政策版本与封账边界
CREATE TABLE IF NOT EXISTS ledger_book (
    book_id          VARCHAR(64) NOT NULL PRIMARY KEY,
    legal_entity_id  VARCHAR(64) NOT NULL,
    policy_version   VARCHAR(32) NOT NULL,
    status           VARCHAR(16) NOT NULL,
    created_at       TIMESTAMP   NOT NULL DEFAULT CURRENT_TIMESTAMP
);

-- 账户：固定币种、归属与正常方向
CREATE TABLE IF NOT EXISTS ledger_account (
    account_id      VARCHAR(160) NOT NULL PRIMARY KEY,
    book_id         VARCHAR(64)  NOT NULL,
    owner_scope     VARCHAR(24)  NOT NULL,
    merchant_id     VARCHAR(64),
    currency        VARCHAR(3)   NOT NULL,
    category        VARCHAR(32)  NOT NULL,
    normal_side     VARCHAR(8)   NOT NULL,
    allow_overdraft BOOLEAN      NOT NULL DEFAULT FALSE,
    created_at      TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP
);

-- 资金控制状态：与源记录原子维护，不用异步报表余额批准资金动作
CREATE TABLE IF NOT EXISTS account_balance (
    account_id      VARCHAR(160) NOT NULL PRIMARY KEY,
    posted_balance  BIGINT       NOT NULL,
    reserved_total  BIGINT       NOT NULL,
    version         INT          NOT NULL,
    updated_at      TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP
);

-- 业务操作唯一键：一次经济动作只产生一份原始凭证
CREATE TABLE IF NOT EXISTS ledger_business_operation (
    operation_key   VARCHAR(240) NOT NULL PRIMARY KEY,
    book_id         VARCHAR(64)  NOT NULL,
    merchant_id     VARCHAR(64),
    operation_type  VARCHAR(32)  NOT NULL,
    business_id     VARCHAR(128) NOT NULL,
    payload_digest  VARCHAR(64)  NOT NULL,
    journal_id      VARCHAR(64)  NOT NULL,
    created_at      TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS ledger_journal (
    journal_id     VARCHAR(64)  NOT NULL PRIMARY KEY,
    book_id        VARCHAR(64)  NOT NULL,
    operation_key  VARCHAR(240) NOT NULL,
    kind           VARCHAR(32)  NOT NULL,
    effective_at   TIMESTAMP    NOT NULL,
    recorded_at    TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP,
    policy_version VARCHAR(32)  NOT NULL,
    CONSTRAINT uk_journal_operation UNIQUE (operation_key)
);

-- 分录只追加：side 为借/贷，金额为正整数，币种取账户币种
CREATE TABLE IF NOT EXISTS ledger_entry (
    entry_id     BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    journal_id   VARCHAR(64)  NOT NULL,
    account_id   VARCHAR(160) NOT NULL,
    side         VARCHAR(8)   NOT NULL,
    amount_minor BIGINT       NOT NULL,
    currency     VARCHAR(3)   NOT NULL,
    created_at   TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP
);

-- 修正关联：补偿/冲正必须引用原凭证并保留审批信息
CREATE TABLE IF NOT EXISTS correction_link (
    correction_journal_id VARCHAR(64)  NOT NULL PRIMARY KEY,
    original_journal_id   VARCHAR(64)  NOT NULL,
    reason                VARCHAR(256) NOT NULL,
    approved_by           VARCHAR(64)  NOT NULL,
    created_at            TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP
);

-- 余额投影：可重建读模型，必须暴露消费水位
CREATE TABLE IF NOT EXISTS balance_projection (
    account_id      VARCHAR(160) NOT NULL PRIMARY KEY,
    posted_balance  BIGINT       NOT NULL,
    active_reserved BIGINT       NOT NULL,
    sequence        BIGINT       NOT NULL,
    as_of           TIMESTAMP    NOT NULL
);

-- 支付成功后的待记账任务；独立于支付投影
CREATE TABLE IF NOT EXISTS payment_posting (
    payment_id VARCHAR(64) NOT NULL PRIMARY KEY,
    status     VARCHAR(24) NOT NULL,
    journal_id VARCHAR(64),
    attempts   INT         NOT NULL DEFAULT 0,
    updated_at TIMESTAMP   NOT NULL DEFAULT CURRENT_TIMESTAMP
);

-- 退款单：独立生命周期，不通过创建另一笔收款表达
CREATE TABLE IF NOT EXISTS refund_order (
    refund_id                VARCHAR(64)  NOT NULL PRIMARY KEY,
    payment_id               VARCHAR(64)  NOT NULL,
    merchant_id              VARCHAR(64)  NOT NULL,
    amount_minor             BIGINT       NOT NULL,
    currency                 VARCHAR(3)   NOT NULL,
    status                   VARCHAR(24)  NOT NULL,
    provider_idempotency_key VARCHAR(128) NOT NULL,
    version                  INT          NOT NULL,
    created_at               TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at               TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uk_refund_provider_key UNIQUE (provider_idempotency_key)
);

CREATE TABLE IF NOT EXISTS refund_idempotency (
    merchant_id     VARCHAR(64)  NOT NULL,
    idempotency_key VARCHAR(128) NOT NULL,
    payload_digest  VARCHAR(64)  NOT NULL,
    refund_id       VARCHAR(64)  NOT NULL,
    created_at      TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP,
    PRIMARY KEY (merchant_id, idempotency_key)
);

-- 退款额度池：成功累计与处理中预留都不超过可退上限
CREATE TABLE IF NOT EXISTS refund_pool (
    payment_id       VARCHAR(64) NOT NULL PRIMARY KEY,
    book_id          VARCHAR(64) NOT NULL,
    merchant_id      VARCHAR(64) NOT NULL,
    currency         VARCHAR(3)  NOT NULL,
    refundable_base  BIGINT      NOT NULL,
    refunded_total   BIGINT      NOT NULL,
    reserved_total   BIGINT      NOT NULL,
    version          INT         NOT NULL,
    updated_at       TIMESTAMP   NOT NULL DEFAULT CURRENT_TIMESTAMP
);

-- 预留：首次确认或释放即终结，UNKNOWN 不得自动释放
CREATE TABLE IF NOT EXISTS refund_reservation (
    refund_id    VARCHAR(64)  NOT NULL PRIMARY KEY,
    payment_id   VARCHAR(64)  NOT NULL,
    account_id   VARCHAR(160) NOT NULL,
    amount_minor BIGINT       NOT NULL,
    currency     VARCHAR(3)   NOT NULL,
    status       VARCHAR(16)  NOT NULL,
    version      INT          NOT NULL,
    created_at   TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at   TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS reservation_event (
    event_id     BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    refund_id    VARCHAR(64)  NOT NULL,
    account_id   VARCHAR(160) NOT NULL,
    event_type   VARCHAR(16)  NOT NULL,
    amount_minor BIGINT       NOT NULL,
    evidence_id  VARCHAR(128),
    created_at   TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS refund_event (
    history_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    refund_id  VARCHAR(64)  NOT NULL,
    status     VARCHAR(24)  NOT NULL,
    detail     VARCHAR(512),
    created_at TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS mock_channel_refund_tx (
    provider_idempotency_key VARCHAR(128) NOT NULL PRIMARY KEY,
    status                   VARCHAR(16)  NOT NULL,
    provider_reference       VARCHAR(128) NOT NULL,
    amount_minor             BIGINT       NOT NULL,
    currency                 VARCHAR(3)   NOT NULL,
    created_at               TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP
);

-- ===== 阶段 3：清分、结算、出款与对账 =====

-- 版本化费用规则：新版本带生效边界，不覆盖既有清分明细
CREATE TABLE IF NOT EXISTS fee_rule (
    rule_version    VARCHAR(32) NOT NULL PRIMARY KEY,
    fee_bps         INT         NOT NULL,
    fixed_fee_minor BIGINT      NOT NULL,
    active          BOOLEAN     NOT NULL,
    effective_at    TIMESTAMP   NOT NULL DEFAULT CURRENT_TIMESTAMP
);

-- 清分明细：item_key 唯一，同一应结项目不能被两个有效批次消费
CREATE TABLE IF NOT EXISTS clearing_entry (
    entry_id     VARCHAR(64)  NOT NULL PRIMARY KEY,
    item_key     VARCHAR(160) NOT NULL,
    item_type    VARCHAR(24)  NOT NULL,
    payment_id   VARCHAR(64),
    refund_id    VARCHAR(64),
    merchant_id  VARCHAR(64)  NOT NULL,
    currency     VARCHAR(3)   NOT NULL,
    gross_minor  BIGINT       NOT NULL,
    fee_minor    BIGINT       NOT NULL,
    net_minor    BIGINT       NOT NULL,
    rule_version VARCHAR(32)  NOT NULL,
    status       VARCHAR(16)  NOT NULL,
    created_at   TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uk_clearing_item_key UNIQUE (item_key)
);

CREATE TABLE IF NOT EXISTS settlement_batch (
    batch_id     VARCHAR(64) NOT NULL PRIMARY KEY,
    merchant_id  VARCHAR(64) NOT NULL,
    currency     VARCHAR(3)  NOT NULL,
    rule_version VARCHAR(32) NOT NULL,
    status       VARCHAR(16) NOT NULL,
    gross_minor  BIGINT      NOT NULL,
    refund_minor BIGINT      NOT NULL,
    fee_minor    BIGINT      NOT NULL,
    net_minor    BIGINT      NOT NULL,
    item_count   INT         NOT NULL,
    frozen_at    TIMESTAMP,
    version      INT         NOT NULL,
    created_at   TIMESTAMP   NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at   TIMESTAMP   NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS settlement_item (
    item_id      VARCHAR(64) NOT NULL PRIMARY KEY,
    batch_id     VARCHAR(64) NOT NULL,
    entry_id     VARCHAR(64) NOT NULL,
    item_type    VARCHAR(24) NOT NULL,
    amount_minor BIGINT      NOT NULL,
    created_at   TIMESTAMP   NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uk_settlement_entry UNIQUE (entry_id)
);

-- 出款单：原外部意图身份固定，超时不得换单号重发
CREATE TABLE IF NOT EXISTS payout_order (
    payout_id                VARCHAR(64)  NOT NULL PRIMARY KEY,
    batch_id                 VARCHAR(64)  NOT NULL,
    merchant_id              VARCHAR(64)  NOT NULL,
    currency                 VARCHAR(3)   NOT NULL,
    amount_minor             BIGINT       NOT NULL,
    status                   VARCHAR(16)  NOT NULL,
    provider_idempotency_key VARCHAR(128) NOT NULL,
    bank_reference           VARCHAR(128),
    journal_id               VARCHAR(64),
    version                  INT          NOT NULL,
    created_at               TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at               TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uk_payout_batch UNIQUE (batch_id),
    CONSTRAINT uk_payout_provider_key UNIQUE (provider_idempotency_key)
);

CREATE TABLE IF NOT EXISTS payout_event (
    event_id   BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    payout_id  VARCHAR(64) NOT NULL,
    status     VARCHAR(24) NOT NULL,
    detail     VARCHAR(512),
    created_at TIMESTAMP   NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS mock_bank_scenario (
    merchant_id VARCHAR(64) NOT NULL PRIMARY KEY,
    scenario    VARCHAR(32) NOT NULL
);

CREATE TABLE IF NOT EXISTS mock_bank_tx (
    provider_idempotency_key VARCHAR(128) NOT NULL PRIMARY KEY,
    status                   VARCHAR(16)  NOT NULL,
    bank_reference           VARCHAR(128) NOT NULL,
    amount_minor             BIGINT       NOT NULL,
    currency                 VARCHAR(3)   NOT NULL,
    created_at               TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP
);

-- 对账报告：文件身份与明细业务标识分别去重
CREATE TABLE IF NOT EXISTS recon_report (
    report_id      VARCHAR(64) NOT NULL PRIMARY KEY,
    provider       VARCHAR(32) NOT NULL,
    report_type    VARCHAR(32) NOT NULL,
    period_start   TIMESTAMP   NOT NULL,
    period_end     TIMESTAMP   NOT NULL,
    file_digest    VARCHAR(64) NOT NULL,
    expected_pages INT         NOT NULL,
    received_pages INT         NOT NULL,
    record_count   INT         NOT NULL,
    total_minor    BIGINT      NOT NULL,
    currency       VARCHAR(3)  NOT NULL,
    status         VARCHAR(16) NOT NULL,
    created_at     TIMESTAMP   NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uk_recon_file UNIQUE (provider, report_type, period_start, period_end, file_digest)
);

CREATE TABLE IF NOT EXISTS recon_page (
    report_id   VARCHAR(64)  NOT NULL,
    page_no     INT          NOT NULL,
    page_digest VARCHAR(64)  NOT NULL,
    PRIMARY KEY (report_id, page_no)
);

CREATE TABLE IF NOT EXISTS recon_record (
    record_id     VARCHAR(64)  NOT NULL PRIMARY KEY,
    report_id     VARCHAR(64)  NOT NULL,
    provider      VARCHAR(32)  NOT NULL,
    record_key    VARCHAR(128) NOT NULL,
    record_type   VARCHAR(24)  NOT NULL,
    business_id   VARCHAR(64),
    amount_minor  BIGINT       NOT NULL,
    currency      VARCHAR(3)   NOT NULL,
    record_digest VARCHAR(64)  NOT NULL,
    created_at    TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uk_recon_record_business UNIQUE (provider, record_key)
);

-- 差错单：逐笔差异不能因汇总相等而关闭
CREATE TABLE IF NOT EXISTS recon_difference (
    difference_id   VARCHAR(64)  NOT NULL PRIMARY KEY,
    report_id       VARCHAR(64)  NOT NULL,
    record_key      VARCHAR(128),
    difference_type VARCHAR(32)  NOT NULL,
    amount_minor    BIGINT       NOT NULL,
    currency        VARCHAR(3)   NOT NULL,
    status          VARCHAR(16)  NOT NULL,
    detail          VARCHAR(512),
    created_at      TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uk_recon_difference UNIQUE (report_id, difference_type, record_key)
);

-- 银行流水：保存分配关系与剩余额，同一流水不可重复消费
CREATE TABLE IF NOT EXISTS bank_statement (
    statement_id    VARCHAR(64)  NOT NULL PRIMARY KEY,
    provider        VARCHAR(32)  NOT NULL,
    bank_reference  VARCHAR(128) NOT NULL,
    direction       VARCHAR(8)   NOT NULL,
    amount_minor    BIGINT       NOT NULL,
    allocated_minor BIGINT       NOT NULL,
    currency        VARCHAR(3)   NOT NULL,
    status          VARCHAR(24)  NOT NULL,
    created_at      TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uk_bank_statement_reference UNIQUE (provider, bank_reference, direction)
);

CREATE TABLE IF NOT EXISTS bank_allocation (
    allocation_id VARCHAR(64) NOT NULL PRIMARY KEY,
    statement_id  VARCHAR(64) NOT NULL,
    entry_id      VARCHAR(64) NOT NULL,
    amount_minor  BIGINT      NOT NULL,
    created_at    TIMESTAMP   NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uk_bank_allocation UNIQUE (statement_id, entry_id)
);

-- ===== 阶段 4：安全、容量与灾备验证 =====

-- 恢复任务租约：以条件更新领取，过期只说明本地执行权失效，不证明外部操作失败
CREATE TABLE IF NOT EXISTS recovery_lease (
    task_name   VARCHAR(64) NOT NULL PRIMARY KEY,
    lease_owner VARCHAR(64),
    lease_token VARCHAR(64),
    expires_at  TIMESTAMP   NOT NULL DEFAULT CURRENT_TIMESTAMP,
    version     INT         NOT NULL DEFAULT 0
);

-- 恢复门禁：灾备演练或证据缺失时暂停受影响重放
CREATE TABLE IF NOT EXISTS recovery_guard (
    guard_key  VARCHAR(64)  NOT NULL PRIMARY KEY,
    paused     BOOLEAN      NOT NULL,
    reason     VARCHAR(256),
    updated_by VARCHAR(64),
    updated_at TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP
);

-- 地域权威：切换时递增 epoch，旧地域写入者不得继续本地写入
CREATE TABLE IF NOT EXISTS authority_scope (
    scope_id      VARCHAR(64) NOT NULL PRIMARY KEY,
    active_region VARCHAR(32) NOT NULL,
    epoch         INT         NOT NULL,
    updated_at    TIMESTAMP   NOT NULL DEFAULT CURRENT_TIMESTAMP
);

-- 迟到效果：切换后抵达的旧写入者效果只记录核查，不直接应用
CREATE TABLE IF NOT EXISTS late_effect (
    late_effect_id VARCHAR(64)  NOT NULL PRIMARY KEY,
    scope_id       VARCHAR(64)  NOT NULL,
    region         VARCHAR(32)  NOT NULL,
    epoch          INT          NOT NULL,
    external_ref   VARCHAR(128) NOT NULL,
    detail         VARCHAR(512),
    status         VARCHAR(16)  NOT NULL,
    created_at     TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uk_late_effect UNIQUE (scope_id, external_ref)
);

-- 敏感操作审批：受益人变更或人工修账需要独立批准
CREATE TABLE IF NOT EXISTS approval_request (
    approval_id  VARCHAR(64)  NOT NULL PRIMARY KEY,
    operation    VARCHAR(48)  NOT NULL,
    target_id    VARCHAR(64)  NOT NULL,
    requested_by VARCHAR(64)  NOT NULL,
    approved_by  VARCHAR(64),
    status       VARCHAR(16)  NOT NULL,
    reason       VARCHAR(256),
    created_at   TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP,
    decided_at   TIMESTAMP
);

-- 安全审计：拒绝的敏感操作同样留痕，明细统一脱敏
CREATE TABLE IF NOT EXISTS security_audit (
    audit_id   VARCHAR(64) NOT NULL PRIMARY KEY,
    actor      VARCHAR(64) NOT NULL,
    action     VARCHAR(48) NOT NULL,
    target_id  VARCHAR(64),
    outcome    VARCHAR(16) NOT NULL,
    detail     VARCHAR(512),
    created_at TIMESTAMP   NOT NULL DEFAULT CURRENT_TIMESTAMP
);

-- 受益人账户：变更只经审批后落地
CREATE TABLE IF NOT EXISTS beneficiary_account (
    merchant_id      VARCHAR(64)  NOT NULL PRIMARY KEY,
    bank_account_ref VARCHAR(128) NOT NULL,
    updated_by       VARCHAR(64)  NOT NULL,
    updated_at       TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP
);
